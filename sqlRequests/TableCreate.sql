PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS Levels (
id INTEGER PRIMARY KEY AUTOINCREMENT,
title VARCHAR(50) NOT NULL,
xp_limit INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS Users (
id INTEGER PRIMARY KEY AUTOINCREMENT,
email VARCHAR(150) UNIQUE NOT NULL,
password VARCHAR(150) NOT NULL,
xp INTEGER DEFAULT 0 CHECK(xp >= 0),
level_id INTEGER NOT NULL DEFAULT 1,
FOREIGN KEY (level_id) REFERENCES Levels(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS Achievements (
id INTEGER PRIMARY KEY AUTOINCREMENT,
title VARCHAR(150) NOT NULL UNIQUE,
description TEXT NOT NULL,
unlock_condition_json TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS UserUnlocks (
id INTEGER PRIMARY KEY AUTOINCREMENT,
user_id INTEGER NOT NULL,
achievement_id INTEGER NOT NULL,
unlocked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
FOREIGN KEY (user_id) REFERENCES Users(id) ON DELETE CASCADE,
FOREIGN KEY (achievement_id) REFERENCES Achievements(id) ON DELETE CASCADE,
UNIQUE (user_id, achievement_id)
);

CREATE TABLE IF NOT EXISTS Statistics (
id INTEGER PRIMARY KEY AUTOINCREMENT,
user_id INTEGER UNIQUE NOT NULL,
speed_wpm INTEGER DEFAULT 0 CHECK(speed_wpm >= 0),
accuracy_pct REAL DEFAULT 0.0 CHECK (accuracy_pct BETWEEN 0.0 AND 100.0),
total_lessons_completed INTEGER DEFAULT 0 CHECK(total_lessons_completed >= 0),
FOREIGN KEY (user_id) REFERENCES Users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS StatsHistory (
id INTEGER PRIMARY KEY AUTOINCREMENT,
user_id INTEGER NOT NULL,
speed_wpm INTEGER NOT NULL CHECK(speed_wpm >= 0),
accuracy_pct REAL NOT NULL CHECK(accuracy_pct BETWEEN 0.0 AND 100.0),
errors_json TEXT NOT NULL,
created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
FOREIGN KEY (user_id) REFERENCES Users(id) ON DELETE CASCADE
);